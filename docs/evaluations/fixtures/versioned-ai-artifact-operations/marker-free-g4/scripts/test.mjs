import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from './runtime.mjs';
import { verify } from './verify.mjs';
const fixture = dirname(dirname(fileURLToPath(import.meta.url)));
const artifactPath = join(fixture, 'artifacts/list.placement.json'); const original = readFileSync(artifactPath, 'utf8');
assert.deepEqual(verify(), []);
assert.match(compile().sql, /ORDER BY w\.id ASC/);
assert.match(compile([{ key: 'name', direction: 'asc' }]).sql, /ORDER BY w\.name ASC, w\.id ASC/);
assert.match(compile([{ key: 'priority', direction: 'desc' }, { key: 'createdAt', direction: 'asc' }]).sql, /CASE WHEN w\.priority/);
assert.throws(() => compile([{ key: 'name', direction: 'up' }]), /invalid sort request/);
assert.throws(() => compile([{ key: 'name', direction: 'asc' }, { key: 'name', direction: 'desc' }]), /invalid sort request/);
assert.throws(() => compile([{ key: 'DROP TABLE work_items', direction: 'asc' }]), /unknown sort key/);
assert.throws(() => compile([{ key: 'name', direction: 'asc' }, { key: 'priority', direction: 'asc' }, { key: 'createdAt', direction: 'asc' }, { key: 'name2', direction: 'asc' }]), /invalid sort count/);
const stale = JSON.parse(original); stale.sourceHash = 'bad'; writeFileSync(artifactPath, JSON.stringify(stale)); assert.match(verify().join(' '), /SOURCE_HASH_MISMATCH/);
const context = JSON.parse(original); context.sortInsertion.beforeText = 'ORDER  BY '; writeFileSync(artifactPath, JSON.stringify(context)); assert.match(verify().join(' '), /BEFORE_CONTEXT_MISMATCH/);
const index = JSON.parse(original); index.sortInsertion.index += 1; writeFileSync(artifactPath, JSON.stringify(index)); assert.match(verify().join(' '), /EXPECTED_TEXT_MISMATCH/);
writeFileSync(artifactPath, original); assert.deepEqual(verify(), []);
console.log('TEST_OK');
