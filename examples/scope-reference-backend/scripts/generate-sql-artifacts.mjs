import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const { runModelGen } = await import(pathToFileURL(resolve(root, '../../packages/cli/dist/commands/model-gen.js')).href);
const queries = [
  ['list', 'listSql', 'src/tickets/list.sql'],
  ['get', 'getSql', 'src/tickets/get.sql'],
  ['assignTicket', 'assignTicketSql', 'src/tickets/assign-ticket.sql'],
  ['insertEvent', 'insertEventSql', 'src/tickets/insert-event.sql'],
];

const sqlText = queries.map(([, exportName, sqlPath]) => {
  const sql = readFileSync(resolve(root, sqlPath), 'utf8');
  return `export const ${exportName} = ${JSON.stringify(sql)} as const;`;
});

const models = Object.fromEntries(queries.map(([id, , sqlPath]) => {
  const model = runModelGen({ sqlFile: sqlPath, rootDir: root, dryRun: true });
  return [id, { analysis: model.analysis, bindings: model.bindings }];
}));

const generatedDir = resolve(root, 'src/tickets/generated');
writeFileSync(resolve(generatedDir, 'sql-text.ts'), [
  '// Generated by Ashiba SQL artifact generation. Do not edit by hand.',
  '// Run `pnpm generate:sql-artifacts` after changing canonical SQL.',
  '',
  ...sqlText,
  '',
].join('\n'));
writeFileSync(resolve(generatedDir, 'query-models.ts'), [
  '// Generated from canonical SQL by Ashiba model-gen. Do not edit by hand.',
  '// Run `pnpm generate:sql-artifacts` after changing canonical SQL.',
  '',
  `export const queryModels = ${JSON.stringify(models, null, 2)} as const;`,
  '',
].join('\n'));
